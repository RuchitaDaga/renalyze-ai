from reportlab.lib.pagesizes import A4
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib import colors
import os
import uuid

def generate_ckd_report_pdf(report_data: dict):
    reports_dir = "reports"
    os.makedirs(reports_dir, exist_ok=True)

    filename = f"ckd_report_{uuid.uuid4().hex}.pdf"
    filepath = os.path.join(reports_dir, filename)

    styles = getSampleStyleSheet()
    doc = SimpleDocTemplate(filepath, pagesize=A4)

    elements = []

    elements.append(Paragraph("<b>Renalyze AI – CKD Prediction Report</b>", styles["Title"]))
    elements.append(Spacer(1, 12))

    elements.append(Paragraph("Prediction Summary", styles["Heading2"]))
    elements.append(Spacer(1, 10))

    table_data = [
        ["Field", "Value"],
        ["Patient Name", report_data.get("name", "N/A")],
        ["Age", report_data.get("age", "N/A")],
        ["Prediction", report_data.get("prediction")],
        ["CKD Stage", report_data.get("stage")],
        ["Risk Level", report_data.get("risk")],
        ["Date", report_data.get("date")]
    ]

    table = Table(table_data, hAlign="LEFT")
    table.setStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.lightgrey),
        ("GRID", (0, 0), (-1, -1), 1, colors.black),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold")
    ])

    elements.append(table)
    elements.append(Spacer(1, 20))

    elements.append(Paragraph("Disclaimer:", styles["Heading3"]))
    elements.append(Paragraph(
        "This report is generated by an AI model for academic purposes only and is not a certified medical diagnosis.",
        styles["Normal"]
    ))

    doc.build(elements)

    return filepath
